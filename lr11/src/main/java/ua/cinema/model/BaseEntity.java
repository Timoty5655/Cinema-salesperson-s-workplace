package ua.cinema.model;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import org.hibernate.proxy.HibernateProxy;

/**
 * Спільні поля сутностей. @MappedSuperclass: окремої таблиці для BaseEntity немає,
 * колонки id і name просто «копіюються» в таблиці movie і screening.
 * (@Entity з наслідуванням означав би поліморфні запити "SELECT b FROM BaseEntity b",
 * які тут не потрібні — фільм і сеанс не взаємозамінні.)
 */
@MappedSuperclass
public abstract class BaseEntity {

    /** IDENTITY — відповідає "GENERATED BY DEFAULT AS IDENTITY" в init.sql. null = ще не збережено. */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    /** Довжину кожна сутність уточнює через @AttributeOverride (у movie — 200, у screening — 100). */
    @Column(name = "name", nullable = false)
    private String name;

    /** Конструктор без параметрів — вимога JPA (Hibernate створює об'єкт через рефлексію). */
    protected BaseEntity() {
    }

    protected BaseEntity(String name) {
        this.name = name;
    }

    public Long getId() {
        return id;
    }

    public boolean isNew() {
        return id == null;
    }

    /** Для сховища в пам'яті, яке, як і БД, саме генерує id. Hibernate встановлює поле напряму. */
    public void assignId(long generatedId) {
        if (id != null) {
            throw new IllegalStateException("id уже призначено: " + id);
        }
        this.id = generatedId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    /**
     * Рівність за id (первинний ключ = ідентичність рядка в таблиці).
     *  - Нові сутності (id == null) рівні лише самі собі.
     *  - Клас порівнюється з урахуванням Hibernate-проксі (LAZY @ManyToOne повертає підклас-проксі).
     *  - id читаємо через getId(): у проксі поля порожні, а метод делегує справжньому об'єкту.
     * Методи не final — інакше Hibernate не зміг би перевизначити їх у проксі.
     */
    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (o == null || effectiveClass(this) != effectiveClass(o)) return false;
        Long otherId = ((BaseEntity) o).getId();
        return getId() != null && getId().equals(otherId);
    }

    /**
     * Константа для класу: hashCode не змінюється, коли persist() призначає id
     * (інакше сутність «загубилася» б у HashSet, куди її поклали до збереження).
     */
    @Override
    public int hashCode() {
        return effectiveClass(this).hashCode();
    }

    private static Class<?> effectiveClass(Object o) {
        return o instanceof HibernateProxy proxy
                ? proxy.getHibernateLazyInitializer().getPersistentClass()
                : o.getClass();
    }
}
