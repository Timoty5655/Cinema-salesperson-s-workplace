-- Схема БД кінотеатру. Скрипт ідемпотентний: IF NOT EXISTS, тому повторний запуск нічого не ламає.

CREATE TABLE IF NOT EXISTS movie (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(200) NOT NULL,
    release_year     INT          NOT NULL,
    duration_minutes INT          NOT NULL,
    genre            VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_movie_year     CHECK (release_year BETWEEN 1888 AND 2100),
    CONSTRAINT ck_movie_duration CHECK (duration_minutes > 0),
    CONSTRAINT ck_movie_genre    CHECK (genre IN ('ACTION', 'COMEDY', 'DRAMA', 'SCI_FI', 'ANIMATION', 'HORROR')),
    -- той самий фільм не можна внести двічі; ремейк (інший рік) - можна
    CONSTRAINT uq_movie_name_year UNIQUE (name, release_year)
);

CREATE TABLE IF NOT EXISTS screening (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100)  NOT NULL,
    movie_id    BIGINT        NOT NULL,
    hall_number INT           NOT NULL,
    start_time  TIMESTAMP     NOT NULL,
    price       NUMERIC(8, 2) NOT NULL,
    CONSTRAINT ck_screening_hall  CHECK (hall_number BETWEEN 1 AND 20),
    CONSTRAINT ck_screening_price CHECK (price > 0),
    -- в одному залі в один час - лише один сеанс
    CONSTRAINT uq_screening_hall_time UNIQUE (hall_number, start_time),
    -- RESTRICT: фільм, на який є сеанси, видалити не можна (див. README)
    CONSTRAINT fk_screening_movie FOREIGN KEY (movie_id) REFERENCES movie (id) ON DELETE RESTRICT
);

-- пошук сеансів фільму (findByMovieId) і перевірка FK при видаленні фільму
CREATE INDEX IF NOT EXISTS idx_screening_movie ON screening (movie_id);
-- сортування за назвою (ORDER BY name, ...)
CREATE INDEX IF NOT EXISTS idx_movie_name ON movie (name);
